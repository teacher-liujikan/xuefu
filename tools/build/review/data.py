    S = ['第一關、數字已經對好位', '第二關、自己把數字寫進格子', '第三關、先寫算式，再用直式算']
    def calc(n, a, op, b):
        r = a + b if op == '＋' else a - b
        tok = 'add' if op == '＋' else 'sub'
        return fill(n, '用直式算算看：', f'{a} {op} {b} ＝ [[n]]', [r], '百對百、十對十、一對一，從個位開始算。' + ('滿 10 要進位。' if op == '＋' else '不夠減要向前一位借 1。'),
                    P('按「下一步」，一位一位看怎麼算：') + f'{{{{{tok}:{a}|{b}}}}}')
    def wq(n, stem, a, op, b, unit):
        r = a + b if op == '＋' else a - b
        tok = 'add' if op == '＋' else 'sub'
        return word(n, stem, f'{a}{op}{b}＝{r}', r, unit, '先想：合起來用加法，拿走、比多少用減法。', P(f'算式：{a}{op}{b}＝{r}') + f'{{{{{tok}:{a}|{b}|{unit}}}}}')
    Q = [dict(q, s='s1') for q in [calc('(1)', 312, '＋', 160), calc('(2)', 251, '＋', 96), calc('(3)', 633, '＋', 158), calc('(4)', 876, '－', 134), calc('(5)', 252, '－', 148), calc('(6)', 100, '－', 31)]]
