def w05():
    S = ['第一關、照著提示填格子', '第二關、自己寫出要變成多少', '第三關、當小偵探：答案合理嗎？']
    def near(n, x, a, b):
        da, db = abs(x - a), abs(b - x); c = a if da < db else b
        return fill(n, f'{x} 比較接近 {a} 還是 {b}？', f'{x} 到 {a} 差 [[s]]，{x} 到 {b} 差 [[s]]<br>比較接近 [[s:{a}|{b}]]', [da, db, c],
                    '算一算到兩邊各差多少，差得少的比較近。', P(f'{x} 到 {a} 差 {da}，{x} 到 {b} 差 {db}。', f'{min(da,db)} 比較少，所以 {x} 比較接近 <b>{c}</b>。'))
    def est(n, x, y, op, rx, ry, opts, full_op=True):
        r = rx + ry if op == '＋' else rx - ry
        exact = x + y if op == '＋' else x - y
        tail = f'最接近 [[s:{"|".join(map(str, opts))}]]'
        if full_op:
            stem = f'{x} 很接近 [[s]]，{y} 很接近 [[s]]<br>[[s]] {op} [[s]] ＝ [[n]]<br>{tail}'; ans = [rx, ry, rx, ry, r, r]
        else:
            stem = f'[[s]] 很接近 [[s]]，[[s]] 很接近 [[s]]<br>[[s]] {OPS} [[s]] ＝ [[n]]<br>{tail}'; ans = [x, rx, y, ry, rx, op, ry, r, r]
        return fill(n, f'{x}{op}{y} 的答案最接近 {"、".join(map(str, opts))} 中哪一個？', stem, ans,
                    '先把兩個數都變成最接近的整十或整百，再算。',
                    P(f'{x} 很接近 <b>{rx}</b>，{y} 很接近 <b>{ry}</b>。', f'{rx}{op}{ry}＝<b>{r}</b>，所以最接近 <b>{r}</b>。',
                      f'真的算一次：{x}{op}{y}＝{exact}，真的很接近 {r}！'))
    def reason(n, who, x, op, y, wrong, rx, ry, okk):
        r = rx + ry if op == '＋' else rx - ry
        return fill(n, f'{who}算出「{x}{op}{y}＝{wrong}」，答案合理嗎？', f'我估：[[s]] {op} [[s]] ＝ [[n]]<br>{wrong} [[s:合理|不合理]]', [rx, ry, r, '合理' if okk else '不合理'],
                    '先估一估大約是多少，再和他的答案比一比，差很多就不合理。',
                    P(f'{x} 大約是 {rx}，{y} 大約是 {ry}，{rx}{op}{ry}＝{r}。',
                      f'{wrong} 和 {r} ' + ('差不多，所以<b>合理</b>。' if okk else f'差太多了，所以<b>不合理</b>。正確答案是 {x+y if op=="＋" else x-y}。')))
    Q = [dict(q, s='s1') for q in [near('(1)', 49, 40, 50), near('(2)', 288, 200, 300), est('(3)', 42, 39, '＋', 40, 40, [70, 80, 90]), est('(4)', 62, 19, '－', 60, 20, [30, 40, 50])]]
    Q += [dict(q, s='s2') for q in [est('(5)', 302, 497, '＋', 300, 500, [700, 800, 900], False), est('(6)', 807, 592, '－', 800, 600, [200, 300, 400], False), est('(7)', 721, 294, '－', 700, 300, [300, 400, 500], False)]]
    Q += [dict(q, s='s3') for q in [reason('(8)', '小祥', 497, '＋', 289, 6186, 500, 300, False), reason('(9)', '大維', 913, '－', 489, 1402, 900, 500, False), reason('(10)', '小美', 398, '＋', 205, 603, 400, 200, True)]]
    return '估算', 'NC-2-4-1', S, Q
