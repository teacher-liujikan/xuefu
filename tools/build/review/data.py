# ======================= 23 加減互逆與驗算 =======================
def w23():
    S = ['第一關、先算再驗算', '第二關、看線段圖找（　）', '第三關、比多、比少']
    def ver(n, a, op, b):
        r = a + b if op == '＋' else a - b
        inv = '減法' if op == '＋' else '加法'
        chk = f'{{{{vert:{r}|{"－" if op=="＋" else "＋"}|{b}|{a}}}}}'
        tok = 'add' if op == '＋' else 'sub'
        return fill(n, '先用直式算，再驗算：', f'{a} {op} {b} ＝ [[n]]<br>驗算用 [[s:加法|減法]]', [r, inv], '加法用減法驗算，減法用加法驗算。',
                    f'{{{{{tok}:{a}|{b}}}}}' + P(f'驗算：用{inv}。{r}{"－" if op=="＋" else "＋"}{b}＝{a}，和原來的數一樣，就算對了！') + chk)
    def barq(n, stem, whole, part, ans, unit, a_lab, b_lab):
        return fill(n, stem, f'[[s]] {OPS} [[s]] ＝ [[n]]<br>答：[[n]] {unit}', [whole, '－', part, ans, ans], '上面是全部，下面是兩個部分。求一個部分：全部－另一個部分。',
                    P(f'全部是 {whole}，知道的部分是 {part}。', f'{whole}－{part}＝<b>{ans}</b>。') + f'{{{{sub:{whole}|{part}|{unit}}}}}', F.bar(f'{whole} {unit}', a_lab, b_lab))
    def mm(n, stem, who_opts, more, a, op, b, unit, why):
        r = a + b if op == '＋' else a - b
        return fill(n, stem, f'誰比較多：[[s:{who_opts}]]<br>[[s]] {OPS} [[s]] ＝ [[n]]', [more, a, op, b, r], '先想清楚誰比較多。求比較多的用加法，求比較少的用減法。', P(why, f'{a}{op}{b}＝<b>{r}</b>，答：{r} {unit}。'))
    Q = [dict(q, s='s1') for q in [ver('(1)', 80, '－', 35), ver('(2)', 19, '＋', 38), ver('(3)', 62, '－', 27), ver('(4)', 25, '＋', 46)]]
    Q += [dict(q, s='s2') for q in [barq('(5)', '丁丁有 48 元，還要存多少元才能買 80 元的筆記本？', 80, 48, 32, '元', '48 元', '（　）'),
        barq('(6)', '1 個麵包和 1 條 65 元的吐司共 83 元，麵包多少元？', 83, 65, 18, '元', '（　）', '65 元'),
        barq('(7)', '哥哥有一些錢，媽媽又給他 8 元，一共有 72 元。哥哥原有多少元？', 72, 8, 64, '元', '（　）', '8 元'),
        barq('(8)', '老師有 65 顆糖，送給學生一些後剩下 47 顆，送了多少顆？', 65, 47, 18, '顆', '（　）', '47 顆')]]
    Q += [dict(q, s='s3') for q in [mm('(9)', '小天有 9 枝鉛筆，小樂比小天多 4 枝，小樂有幾枝？', '小天|小樂', '小樂', 9, '＋', 4, '枝', '「小樂比小天多」，小樂比較多，用加法。'),
        mm('(10)', '小天有 30 元，小樂比小天少 10 元，小樂有幾元？', '小天|小樂', '小天', 30, '－', 10, '元', '「小樂比小天少」，小天比較多，小樂比較少，用減法。'),
        mm('(11)', '姐姐有 11 張貼紙，姐姐比妹妹多 4 張，妹妹有幾張？', '姐姐|妹妹', '姐姐', 11, '－', 4, '張', '「姐姐比妹妹多」，姐姐比較多，妹妹比較少，用減法。小心不要看到「多」就用加法！'),
        mm('(12)', '弟弟有 35 顆彈珠，弟弟比哥哥少 20 顆，哥哥有幾顆？', '弟弟|哥哥', '哥哥', 35, '＋', 20, '顆', '「弟弟比哥哥少」，就是哥哥比較多，要用加法。小心不要看到「少」就用減法！')]]
    return '加減互逆和驗算', 'NC-2-3-1', S, Q
