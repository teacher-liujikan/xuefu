import re
import figs as F

def web(svg, k=3.6):
    """mm-sized print SVG -> px-sized web SVG"""
    return re.sub(r'width="([\d.]+)mm" height="([\d.]+)mm"', lambda m: f'width="{float(m.group(1))*k:.0f}" height="{float(m.group(2))*k:.0f}"', svg)

def unitbar(n, unit_w, label, color='#ffd3a6'):
    out = [F.T(2, 5.6, label, 3.4, 'start')]
    for i in range(n):
        out.append(f'<rect x="{22+i*unit_w}" y="1.5" width="{unit_w}" height="5" fill="{color}" stroke="#1b2a30" stroke-width=".3"/>')
    return F.svg(24 + n * unit_w, 8, ''.join(out))

def fill(n, ask, stem, ans, hint, ex, fig=''):
    return dict(type='fill', n=n, ask=ask, stem=stem, ans=[str(a) for a in ans], hint=hint, ex=ex, fig=web(fig) if fig else '')
def word(n, stem, f, ans, unit, hint, ex, fig=''):
    return dict(type='word', n=n, stem=stem, f=f, ans=ans, unit=unit, hint=hint, ex=ex, fig=web(fig) if fig else '')
def word2(n, stem, f1, f2, ans, unit, hint, ex):
    return dict(type='word2', n=n, stem=stem, f1=f1, f2=f2, ans=ans, unit=unit, hint=hint, ex=ex, fig='')
def opn(n, stem, ansText, hint, ex, fig=''):
    return dict(type='open', n=n, stem=stem, ansText=ansText, hint=hint, ex=ex, fig=web(fig) if fig else '')
def P(*lines): return ''.join(f'<p>{l}</p>' for l in lines)

